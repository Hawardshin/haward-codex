import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { publicReleaseTargetDir } from "./public-release-config.mjs";
import { repoRoot } from "./desktop-pipeline/paths.mjs";

export const defaultPublicReleaseDevDir = path.join(publicReleaseTargetDir, "dev");

const defaultEndpoint = "https://updates.example.invalid/agent-workspace-platform/latest.json";
const defaultAssetBaseUrl = "https://updates.example.invalid/agent-workspace-platform";

export function buildPublicReleaseDevEnvReport({
  writeFiles = false,
  force = false,
  devDir = defaultPublicReleaseDevDir,
  endpoint = defaultEndpoint,
  assetBaseUrl = defaultAssetBaseUrl,
  generateKeyPair = generateTauriKeyPair
} = {}) {
  const privateKeyPath = path.join(devDir, "tauri-updater-dev.key");
  const publicKeyPath = `${privateKeyPath}.pub`;
  const envFilePath = path.join(devDir, "public-release-dev.env.sh");

  if (writeFiles) {
    mkdirSync(devDir, { recursive: true });
    const privateKeyExists = existsSync(privateKeyPath);
    const publicKeyExists = existsSync(publicKeyPath);
    if ((!privateKeyExists && !publicKeyExists) || force) {
      generateKeyPair({ privateKeyPath, publicKeyPath, force });
    }
  }

  const privateKeyExists = existsSync(privateKeyPath);
  const publicKeyExists = existsSync(publicKeyPath);
  const publicKey = publicKeyExists ? readFileSync(publicKeyPath, "utf8").trim() : "";
  const blockers = [];
  if (!privateKeyExists) {
    blockers.push("Missing local dev updater private key. Run with --write to generate one under src-tauri/target/public-release/dev/.");
  }
  if (!publicKey) {
    blockers.push("Missing local dev updater public key. Run with --write to generate one under src-tauri/target/public-release/dev/.");
  }
  if (privateKeyExists && !publicKeyExists) {
    blockers.push("The private key exists but the public key file is missing. Use --force only if this local dev key can be replaced.");
  }

  if (writeFiles && blockers.length === 0) {
    writeFileSync(envFilePath, buildEnvFile({ privateKeyPath, publicKey, endpoint, assetBaseUrl }));
  }

  return {
    status: blockers.length ? "public_release_dev_env_blocked" : "public_release_dev_env_ready",
    blockers,
    warnings: [
      "This dev env only prepares local updater signing/config inputs.",
      "Developer ID signing and Apple notarization credentials are still required for real public distribution."
    ],
    paths: {
      privateKeyPath,
      publicKeyPath,
      envFilePath: existsSync(envFilePath) ? envFilePath : null
    },
    envSummary: {
      updaterPrivateKeyPathPresent: privateKeyExists,
      updaterPublicKeySha25616: publicKey ? sha256Short(publicKey) : null,
      updaterEndpoint: endpoint,
      releaseAssetBaseUrl: assetBaseUrl
    },
    nextCommands: existsSync(envFilePath)
      ? [
          `source ${shellQuote(envFilePath)}`,
          "corepack pnpm run desktop:release:report",
          "corepack pnpm run desktop:package:public"
        ]
      : [
          "corepack pnpm run desktop:release:dev-env",
          "source platform-desktop-app/src-tauri/target/public-release/dev/public-release-dev.env.sh"
        ],
    secretBoundary: [
      "The private updater key is generated only under ignored src-tauri/target/.",
      "The generated shell env file stores TAURI_SIGNING_PRIVATE_KEY_PATH, not the private key content.",
      "Apple signing and notarization credentials are never generated or stored by this script."
    ]
  };
}

function buildEnvFile({ privateKeyPath, publicKey, endpoint, assetBaseUrl }) {
  return [
    "# Generated by scripts/public-release-dev-env.mjs for local developer diagnosis only.",
    "# Do not use this dev updater key for production releases.",
    `export TAURI_SIGNING_PRIVATE_KEY_PATH=${shellQuote(privateKeyPath)}`,
    `export TAURI_UPDATER_PUBLIC_KEY=${shellQuote(publicKey)}`,
    `export TAURI_UPDATER_ENDPOINTS=${shellQuote(endpoint)}`,
    `export TAURI_RELEASE_ASSET_BASE_URL=${shellQuote(assetBaseUrl)}`,
    ""
  ].join("\n");
}

function generateTauriKeyPair({ privateKeyPath, force }) {
  const args = [
    "pnpm",
    "--filter",
    "platform-desktop-app",
    "exec",
    "tauri",
    "signer",
    "generate",
    "--ci",
    "-w",
    privateKeyPath
  ];
  if (force) {
    args.push("--force");
  }
  const result = spawnSync("corepack", args, {
    cwd: repoRoot,
    env: process.env,
    stdio: "inherit",
    shell: false
  });
  if (result.error) {
    throw new Error(`Failed to start Tauri signer: ${result.error.message}`);
  }
  if (result.status !== 0) {
    throw new Error(`Tauri signer failed with exit status ${result.status ?? 1}`);
  }
}

function shellQuote(value) {
  return `'${String(value).replace(/'/g, "'\\''")}'`;
}

function sha256Short(value) {
  return createHash("sha256").update(value).digest("hex").slice(0, 16);
}

function parseArgs(argv) {
  return {
    writeFiles: argv.includes("--write"),
    force: argv.includes("--force"),
    endpoint: valueAfter(argv, "--endpoint") || defaultEndpoint,
    assetBaseUrl: valueAfter(argv, "--asset-base-url") || defaultAssetBaseUrl,
    devDir: valueAfter(argv, "--dir") || defaultPublicReleaseDevDir
  };
}

function valueAfter(argv, flag) {
  const index = argv.indexOf(flag);
  return index >= 0 ? argv[index + 1] : "";
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    const report = buildPublicReleaseDevEnvReport(parseArgs(process.argv.slice(2)));
    console.log(JSON.stringify(report, null, 2));
    if (report.blockers.length) {
      process.exitCode = 1;
    }
  } catch (error) {
    console.error(JSON.stringify({
      status: "public_release_dev_env_failed",
      error: error instanceof Error ? error.message : String(error)
    }, null, 2));
    process.exitCode = 1;
  }
}
